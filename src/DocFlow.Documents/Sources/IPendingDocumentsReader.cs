namespace DocFlow.Documents;

/// <summary>
/// Описание ОДНОЙ вьюхи сторонней БД как источника документов: «если вьюха вернула запись — документ ждёт обработки».
/// Вьюх может быть несколько. Одна вьюха может отдавать документы РАЗНЫХ типов (например, view_1: сценарии 1 и 4):
/// тип по записи определяют правила Matches маршрутов, поэтому в Data кладите все колонки, нужные для распознавания.
/// Классы, реализующие этот интерфейс, подхватываются автоматически (AddDocFlowDocuments).
/// </summary>
public interface IPendingDocumentsReader
{
    /// <summary>
    /// Уникальный идентификатор источника (константа из <see cref="SourceIds"/>). Входит в ключ дедупликации
    /// (SourceId, ExternalId, Run): у разных вьюх идентификаторы документов могут совпадать. Уникальность проверяется при старте.
    /// </summary>
    string SourceId { get; }

    /// <summary>SELECT из вьюхи: все записи, которые сейчас ждут обработки.</summary>
    Task<IReadOnlyList<PendingDocument>> ReadAsync(CancellationToken ct);
}
